import { describe, it, expect, beforeEach, spyOn, afterEach, mock } from "bun:test";
import axios from "axios";
import { getConfig, resetConfig } from "../src/config.ts";
import {
  generateTokenIdentity,
  callByteDanceModelArk,
  TokenIdentitySchema,
  SYSTEM_PROMPT,
} from "../src/modules/ai/gemini-brain.ts";

// ---------------------------------------------------------------------------
// Shared fixture: a valid TokenIdentity JSON string used across multiple tests.
// Represents the minimal correct output any AI provider must produce.
// ---------------------------------------------------------------------------
const VALID_TOKEN_FIXTURE = {
  name: "Gemini Token",
  ticker: "GMNI",
  description: "A verified test token generated by the primary AI provider pipeline",
  viralScore: 90,
  imagePrompt: "futuristic gemstone glowing electric blue, crypto art vector sticker style",
  website: "https://geminitoken.xyz",
  twitter: "https://x.com/geminitoken",
  telegram: "https://t.me/geminitoken",
};

// ---------------------------------------------------------------------------
// Mock @google/generative-ai so Gemini tests run fully offline.
// Bun hoists mock.module() calls — this applies before any module imports.
// The mock returns VALID_TOKEN_FIXTURE. Tests that delete
// GOOGLE_GENERATIVE_AI_API_KEY are unaffected because the Gemini code path
// is guarded by: if (cfg.GOOGLE_GENERATIVE_AI_API_KEY && ...)
// ---------------------------------------------------------------------------
mock.module("@google/generative-ai", () => ({
  GoogleGenerativeAI: class MockGoogleGenerativeAI {
    // eslint-disable-next-line @typescript-eslint/no-useless-constructor
    constructor(_apiKey: string) {}
    getGenerativeModel(_opts: unknown) {
      return {
        startChat: (_config: unknown) => ({
          sendMessage: async (_prompt: string) => ({
            response: {
              text: () => JSON.stringify(VALID_TOKEN_FIXTURE),
            },
          }),
        }),
      };
    }
  },
}));


describe("AI Multi-Provider Fallback & English-First Generation", () => {
  let axiosPostSpy: ReturnType<typeof spyOn>;

  beforeEach(() => {
    resetConfig();
    process.env.FIRECRAWL_API_KEY = "test_firecrawl";
    process.env.PINATA_JWT = "test_pinata";
    process.env.EVM_PRIVATE_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";
    process.env.SOLANA_PRIVATE_KEY = "4wBqpZM9xaSheZzBSPRHKJHsNYmAQhFocDPStpwFnGRHaKHt64VpR1LPMaxpCjBFRcYCLFUJL4kP18tJbRBr7HRQ";
    delete process.env.GOOGLE_GENERATIVE_AI_API_KEY;
    delete process.env.BYTEDANCE_ARK_API_KEY;
    axiosPostSpy = spyOn(axios, "post");
  });

  afterEach(() => {
    axiosPostSpy?.mockRestore();
  });

  it("1. should validate config when only ByteDance ModelArk key is configured (Gemini absent)", () => {
    process.env.BYTEDANCE_ARK_API_KEY = "ark-test-key";
    process.env.BYTEDANCE_MODEL_ENDPOINT = "ep-test-endpoint";
    resetConfig();

    const cfg = getConfig();
    expect(cfg.BYTEDANCE_ARK_API_KEY).toBe("ark-test-key");
    expect(cfg.BYTEDANCE_MODEL_ENDPOINT).toBe("ep-test-endpoint");
    expect(cfg.GOOGLE_GENERATIVE_AI_API_KEY).toBeUndefined();
  });

  it("2. should validate config when only Gemini key is configured", () => {
    process.env.GOOGLE_GENERATIVE_AI_API_KEY = "ai-test-key";
    resetConfig();

    const cfg = getConfig();
    expect(cfg.GOOGLE_GENERATIVE_AI_API_KEY).toBe("ai-test-key");
    expect(cfg.BYTEDANCE_ARK_API_KEY).toBeUndefined();
  });

  it("3. SYSTEM_PROMPT should strictly enforce English rules and pure JSON format", () => {
    expect(SYSTEM_PROMPT).toContain("ALL FIELDS MUST BE IN ENGLISH");
    expect(SYSTEM_PROMPT).toContain("Ticker MUST be all-caps");
    expect(SYSTEM_PROMPT).toContain("STRICT PURE JSON");
  });

  it("4. callByteDanceModelArk should successfully call BytePlus endpoint and parse English TokenIdentity", async () => {
    process.env.BYTEDANCE_ARK_API_KEY = "ark-valid-key";
    process.env.BYTEDANCE_MODEL_ENDPOINT = "ep-20260906092451-nzlwx";
    process.env.BYTEDANCE_BASE_URL = "https://ark.ap-southeast.bytepluses.com/api/v3";
    resetConfig();
    const cfg = getConfig();

    const mockAiJson = JSON.stringify({
      name: "Galactic Doge",
      ticker: "GDOGE",
      description: "First astronaut dog riding high on decentralized rails to Mars",
      viralScore: 95,
      imagePrompt: "cute space dog wearing glass helmet on red planet, vibrant cartoon style",
      website: "https://galacticdoge.xyz",
      twitter: "https://x.com/galacticdoge",
      telegram: "https://t.me/galacticdoge",
    });

    axiosPostSpy.mockResolvedValueOnce({
      status: 200,
      data: {
        choices: [
          {
            message: {
              content: mockAiJson,
            },
          },
        ],
      },
    });

    const result = await callByteDanceModelArk("Trending: Mars exploration with cyber dog", cfg);

    expect(result).not.toBeNull();
    expect(result!.name).toBe("Galactic Doge");
    expect(result!.ticker).toBe("GDOGE");
    expect(result!.viralScore).toBe(95);

    // Verify axios call arguments
    expect(axiosPostSpy).toHaveBeenCalledTimes(1);
    const calledUrl = axiosPostSpy.mock.calls[0][0];
    const calledBody = axiosPostSpy.mock.calls[0][1];
    const calledHeaders = axiosPostSpy.mock.calls[0][2]?.headers;

    expect(calledUrl).toBe("https://ark.ap-southeast.bytepluses.com/api/v3/chat/completions");
    expect(calledBody.model).toBe("ep-20260906092451-nzlwx");
    expect(calledHeaders.Authorization).toBe("Bearer ark-valid-key");
  });

  it("5. generateTokenIdentity should automatically fallback to ByteDance when Gemini is unconfigured", async () => {
    process.env.BYTEDANCE_ARK_API_KEY = "ark-fallback-key";
    process.env.BYTEDANCE_MODEL_ENDPOINT = "ep-test";
    resetConfig();

    const mockAiJson = JSON.stringify({
      name: "Solar Chad",
      ticker: "SCHAD",
      description: "Harnessing the solar flare energy for maximum staking gains",
      viralScore: 88,
      imagePrompt: "golden muscular lion with sunglasses standing on sun beam",
      website: "https://solarchad.io",
      twitter: "https://x.com/solarchad",
      telegram: "https://t.me/solarchad",
    });

    axiosPostSpy.mockResolvedValueOnce({
      status: 200,
      data: {
        choices: [
          {
            message: {
              content: mockAiJson,
            },
          },
        ],
      },
    });

    const result = await generateTokenIdentity("Raw solar flares trending data");

    expect(result).not.toBeNull();
    expect(result!.ticker).toBe("SCHAD");
    expect(result!.name).toBe("Solar Chad");
    expect(axiosPostSpy).toHaveBeenCalledTimes(1);
  });

  it("6. TokenIdentitySchema should reject non-alphanumeric tickers or names", () => {
    const invalidTicker = {
      name: "Valid Name",
      ticker: "INVALID_TICKER_TOO_LONG",
      description: "Valid description over 10 chars",
      viralScore: 80,
      imagePrompt: "Valid image prompt",
      website: "https://test.com",
      twitter: "https://x.com/test",
      telegram: "https://t.me/test",
    };

    const parseResult = TokenIdentitySchema.safeParse(invalidTicker);
    expect(parseResult.success).toBe(false);
  });

  // ─────────────────────────────────────────────────────────────────────────
  // P1 TESTS — Previously missing coverage (added in hardening pass)
  // ─────────────────────────────────────────────────────────────────────────

  it("7. Gemini success: BytePlus axios must NOT be called", async () => {
    // Arrange: configure both providers. GoogleGenerativeAI is mocked at module
    // level to return VALID_TOKEN_FIXTURE. If Gemini succeeds, Stage 2 (BytePlus)
    // must never execute — axiosPostSpy must remain at 0 calls.
    process.env.GOOGLE_GENERATIVE_AI_API_KEY = "ai-key-for-gemini-success-test";
    process.env.BYTEDANCE_ARK_API_KEY = "ark-key-also-configured";
    resetConfig();

    const result = await generateTokenIdentity("trend data for Gemini success test");

    // Gemini mock produces a valid TokenIdentity — result must be non-null
    expect(result).not.toBeNull();
    expect(result!.ticker).toBe("GMNI");

    // BytePlus (axios.post) must NOT have been called — Gemini short-circuited
    expect(axiosPostSpy).not.toHaveBeenCalled();
  });

  it("8. Both providers fail: generateTokenIdentity returns null without throwing", async () => {
    // Arrange: only BytePlus configured (Gemini absent). BytePlus will reject all
    // 3 attempts with a network error. The function must return null — never throw.
    process.env.BYTEDANCE_ARK_API_KEY = "ark-fail-test-key";
    delete process.env.GOOGLE_GENERATIVE_AI_API_KEY;
    resetConfig();

    // Make every axios.post attempt fail
    axiosPostSpy.mockRejectedValue(new Error("Network failure simulated"));

    // Act — must not throw even though both providers fail
    const result = await generateTokenIdentity("trend data — both providers failing");

    // Assert: safe null return, not a thrown exception
    expect(result).toBeNull();

    // Assert: all 3 retry attempts were made (proves retry loop ran to exhaustion)
    expect(axiosPostSpy).toHaveBeenCalledTimes(3);
  }, 20000); // 6 s real backoff (2s + 4s between retries) + buffer

  it("9. BytePlus HTTP 5xx: retries 3 times then returns null", async () => {
    // Arrange: simulate a 500 Internal Server Error from BytePlus on every attempt.
    process.env.BYTEDANCE_ARK_API_KEY = "ark-5xx-test-key";
    process.env.BYTEDANCE_MODEL_ENDPOINT = "ep-test-5xx";
    resetConfig();

    // Construct a minimal AxiosError-shaped object with HTTP status
    const http500Error = Object.assign(
      new Error("Request failed with status code 500"),
      {
        name: "AxiosError",
        code: "ERR_BAD_RESPONSE",
        response: { status: 500, data: { error: "Internal Server Error" } },
      }
    );
    axiosPostSpy.mockRejectedValue(http500Error);

    const result = await callByteDanceModelArk("trend data — 5xx test", getConfig());

    // Must return null after exhausting retries — never throw
    expect(result).toBeNull();

    // All 3 attempts must have been made
    expect(axiosPostSpy).toHaveBeenCalledTimes(3);
  }, 20000); // 6 s real backoff (2s + 4s) + buffer

  it("10. BytePlus network timeout: retries 3 times then returns null", async () => {
    // Arrange: simulate an axios ECONNABORTED (25 s timeout exceeded) on every attempt.
    process.env.BYTEDANCE_ARK_API_KEY = "ark-timeout-test-key";
    process.env.BYTEDANCE_MODEL_ENDPOINT = "ep-test-timeout";
    resetConfig();

    // Construct a minimal timeout error (ECONNABORTED is what axios emits on timeout)
    const timeoutError = Object.assign(
      new Error("timeout of 25000ms exceeded"),
      {
        name: "AxiosError",
        code: "ECONNABORTED",
      }
    );
    axiosPostSpy.mockRejectedValue(timeoutError);

    const result = await callByteDanceModelArk("trend data — timeout test", getConfig());

    // Must return null — not throw — after retry exhaustion
    expect(result).toBeNull();

    // All 3 attempts must have been made
    expect(axiosPostSpy).toHaveBeenCalledTimes(3);
  }, 20000); // 6 s real backoff (2s + 4s) + buffer
});
